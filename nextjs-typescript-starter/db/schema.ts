// 新增表
export type UserRow = typeof users.$inferSelect;
export type UserInsert = typeof users.$inferInsert;
export type UserBookProgressRow = typeof userBookProgress.$inferSelect;
export type UserBookProgressInsert = typeof userBookProgress.$inferInsert;
export type UserWordRecordRow = typeof userWordRecords.$inferSelect;
export type UserWordRecordInsert = typeof userWordRecords.$inferInsert;

/** 学习状态枚举（与 user_word_records.status 的 check 约束保持一致） */
export const WORD_STATUSES = ["learning", "known", "unknown"] as const;
export type WordStatus = (typeof WORD_STATUSES)[number];

